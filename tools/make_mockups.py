"""Generates the design previews of the interface into docs/specs/mockups/previews/ (one WebP per scene) and their
index (README.md there).

Adapted from Azeroth Accord (tools/make_mockups.py, itself from Azeroth Guild Finder and Finland Dragon Credit
Points), same owner, GPL-3.0 (ADR 0012); its annotated spec pages and comparison sheet are not needed here. Every image
is drawn from the addon's own layout, colours (UI/Theme.lua) and texts (Locales/), with original art only (ADR 0013).
Nothing has been run in the real WoW client yet, so each image carries a "Design preview" strip at the bottom.

Usage:
    python -X utf8 tools/make_mockups.py              all images
    python -X utf8 tools/make_mockups.py settings     only the images whose name contains the text
    python -X utf8 tools/make_mockups.py --index      only rewrite previews/README.md (no browser needed)
    python -X utf8 tools/make_mockups.py --html DIR   write the pages into DIR (to look at them in a browser)

Needs headless Chrome or Edge (the CHROME environment variable overrides the search) and Pillow. tools/check_docs.py
calls check(), which needs neither: every scene builds from the addon's files, has its image and is in the index.
"""
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, "docs", "specs", "mockups", "previews")
W, H, STRIP = 1200, 720, 34

STRIPS = {
    "enUS": ("DESIGN PREVIEW", "Design preview, not a screenshot: nothing has run in WoW Forever yet"),
    "itIT": ("ANTEPRIMA DI PROGETTO",
             "Anteprima di progetto, non è uno screenshot: nulla è ancora stato provato in WoW Forever"),
}


def render_scene(scene):
    """The HTML of one scene, with {ASSETS} and {FONTS} still to be replaced."""
    import mockup_lib as lib
    name, caption, build, lang, theme = scene
    label, text = STRIPS[lang]
    lib.set_lang(lang)
    try:
        body, style = build(), lib.css(theme)
    finally:
        lib.set_lang("enUS")
    return (f'<!doctype html><html lang="{lang[:2]}"><head><meta charset="utf-8"><title>{name}</title>'
            f'<style>{style}</style></head><body><div class="stage">{body}</div>'
            f'<div class="dp" title="{lib.esc(caption)}"><b>{label}</b><span class="r">{text}</span></div></body></html>')


def fill(html):
    def url(*parts):
        return pathlib.Path(ROOT, *parts).as_uri()
    return html.replace("{ASSETS}", url("assets")).replace("{FONTS}", url("AzerothThreatwarden", "Media", "Fonts"))


def find_browser():
    pf, pf86 = os.environ.get("ProgramFiles", ""), os.environ.get("ProgramFiles(x86)", "")
    candidates = [os.environ.get("CHROME", "")]
    for base in (pf, pf86):
        candidates += [os.path.join(base, "Google", "Chrome", "Application", "chrome.exe"),
                       os.path.join(base, "Microsoft", "Edge", "Application", "msedge.exe")]
    candidates += ["/usr/bin/google-chrome", "/usr/bin/chromium", "/usr/bin/chromium-browser",
                   "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"]
    for path in candidates:
        if path and os.path.isfile(path):
            return path
    for name in ("google-chrome", "chromium", "chrome", "msedge"):
        if shutil.which(name):
            return shutil.which(name)
    sys.exit("No Chrome or Edge found: set the CHROME environment variable to its path.")


def to_webp(png, webp):
    """The browser's PNG becomes a lossy WebP (quality 80): flat panels and text stay sharp at a few tens of KB."""
    from PIL import Image
    Image.open(png).convert("RGB").save(webp, "WEBP", quality=80, method=6)


GROUPS = [("The threat monitor", "monitor-"), ("Alerts and Coach", ("coach-", "alert-")),
          ("Reports", ("reports-", "report-values-", "report-state-", "report-unknown-")),
          ("Timeline and replay", ("replay-", "report-timeline-")), ("The window", "window-"), ("Settings", "settings-"), ("Info and credits", "about-")]


def index_text(scenes):
    lines = ["# Interface previews", "",
             "The threat monitor, the alerts and the Coach, the reports, the timeline and the replay, the window, the Settings page "
             "and the Info page of Azeroth Threatwarden, in both languages of the interface (players and mobs are invented).", "",
             "> **Design previews, not screenshots.** Drawn from the addon's layout, colours (`UI/Theme.lua`) and texts "
             "(`Locales/`), with original art only (CSS shapes, the addon's logo, the NEBULA logos and the fonts the "
             "addon ships). Nothing has been run in WoW Forever yet, so the real window may differ in small details "
             "(fonts, textures, exact spacing). Every image says so in its bottom strip.", "",
             "Written by `python -X utf8 tools/make_mockups.py`: do not edit this file.", ""]
    for title, prefix in GROUPS:
        lines += [f"## {title}", "", "| Preview | What it shows |", "|---|---|"]
        for name, caption, _, _, _ in scenes:
            if name.startswith(prefix):
                lines.append(f"| [![{caption}]({name}.webp)]({name}.webp) | **{name}**<br>{caption} |")
        lines.append("")
    return "\n".join(lines)


def check(problems):
    """Called by tools/check_docs.py (no browser, no Pillow)."""
    try:
        from mockup_scenes import SCENES
        names = [s[0] for s in SCENES]
        if len(names) != len(set(names)):
            problems.append("tools/make_mockups.py: two scenes have the same name")
        for scene in SCENES:
            if len(render_scene(scene)) < 2000:
                problems.append(f"tools/make_mockups.py: the scene {scene[0]} is almost empty")
            image = os.path.join(OUT, scene[0] + ".webp")
            if not os.path.isfile(image) or os.path.getsize(image) == 0:
                problems.append(f"docs/specs/mockups/previews/{scene[0]}.webp is missing: run tools/make_mockups.py")
        known = {name + ".webp" for name in names} | {"README.md"}
        for f in sorted(os.listdir(OUT)) if os.path.isdir(OUT) else []:
            if f not in known:
                problems.append(f"docs/specs/mockups/previews/{f} is not made by tools/make_mockups.py: delete it")
        readme = os.path.join(OUT, "README.md")
        text = ""
        if os.path.isfile(readme):
            with open(readme, encoding="utf-8", newline="") as f:
                text = f.read()
        if text != index_text(SCENES):
            problems.append("docs/specs/mockups/previews/README.md is out of date: "
                            "run python -X utf8 tools/make_mockups.py --index")
    except Exception as e:  # noqa: BLE001 - a broken generator is a problem to report, not a crash
        problems.append(f"tools/make_mockups.py: the scenes do not build: {type(e).__name__}: {e}")


def screenshot(chrome, html, folder, name):
    source = os.path.join(folder, name + ".html")
    with open(source, "w", encoding="utf-8", newline="\n") as f:
        f.write(html)
    png = os.path.join(folder, name + ".png")
    subprocess.run([chrome, "--headless=new", "--disable-gpu", "--hide-scrollbars", "--force-device-scale-factor=1",
                    "--allow-file-access-from-files", f"--user-data-dir={os.path.join(folder, 'profile')}",
                    f"--window-size={W},{H + STRIP}", "--virtual-time-budget=3000", f"--screenshot={png}",
                    pathlib.Path(source).as_uri()],
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=True, timeout=120)
    return png


def main():
    from mockup_scenes import SCENES
    args = sys.argv[1:]
    os.makedirs(OUT, exist_ok=True)
    if "--html" in args:
        folder = args[args.index("--html") + 1]
        os.makedirs(folder, exist_ok=True)
        for scene in SCENES:
            with open(os.path.join(folder, scene[0] + ".html"), "w", encoding="utf-8", newline="\n") as f:
                f.write(fill(render_scene(scene)))
        print(f"{len(SCENES)} pages written to {folder}")
        return
    if "--index" not in args:
        only = args[0] if args else ""
        chrome = find_browser()
        with tempfile.TemporaryDirectory(prefix="aztw-mockups-", ignore_cleanup_errors=True) as tmp:
            for scene in SCENES:
                name = scene[0]
                if only in name:
                    webp = os.path.join(OUT, name + ".webp")
                    to_webp(screenshot(chrome, fill(render_scene(scene)), tmp, name), webp)
                    print(f"{name}.webp  {os.path.getsize(webp) // 1024} KB")
    with open(os.path.join(OUT, "README.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write(index_text(SCENES))
    print(f"{len(SCENES)} scenes, index written to docs/specs/mockups/previews/README.md")


if __name__ == "__main__":
    main()
