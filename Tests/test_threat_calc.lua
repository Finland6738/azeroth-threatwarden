-- Data/ThreatCalc.lua (SPEC-02 §2, SPEC-03 §2.2, §2.5, ADR 0003): known series with known answers (exact slopes),
-- noise and the three confidences, too few samples or too short a span (Insufficient data), gaps, stale and duplicate
-- samples, a constant series; the margin of a non tank and of the tank (the second, no one else, no one readable); the
-- time to overtake (conditions, at most 10 s, rounding up) and the predicted WARNING; the freshness threshold.

local function C() return Mock.ns.ThreatCalc end

-- A ring filled with p(t) at the given times.
local function series(times, fn)
	local s = C().NewSamples()
	for _, t in ipairs(times) do C().Push(s, t, fn(t)) end
	return s
end

local function every(from, to, step)
	local list = {}
	for i = 0, math.floor((to - from) / step + 1e-6) do list[#list + 1] = from + i * step end
	return list
end

-- A small fixed "noise" (no random numbers: the answers must be the same on every run).
local WOBBLE = { 0.6, -1.1, 0.9, -0.4, 1.2, -0.8, 0.3, -1.3, 1.0, -0.5, 0.7, -0.9, 0.2, -0.6, 1.1 }

describe("the trend: known series (SPEC-03 §2.5)", function()
	it("gives the exact slope of a straight line", function()
		local s = series(every(10, 12, 0.2), function(t) return 40 + 6 * (t - 10) end)
		local slope, confidence, n, r2 = C().Trend(s, 12)
		near(slope, 6, 1e-9)
		eq(confidence, "high")
		eq(n, 11)
		near(r2, 1, 1e-9)
	end)

	it("gives a negative slope for a falling line", function()
		local s = series(every(0, 2, 0.25), function(t) return 90 - 4.5 * t end)
		local slope, confidence = C().Trend(s, 2)
		near(slope, -4.5, 1e-9)
		eq(confidence, "high")
	end)

	it("gives 0 with R² = 1 for a constant series", function()
		local s = series(every(5, 7, 0.2), function() return 62 end)
		local slope, confidence, n, r2 = C().Trend(s, 7)
		near(slope, 0, 1e-12)
		eq(r2, 1)
		eq(confidence, "high")
		eq(n, 11)
	end)

	it("looks only at the last 3 s", function()
		-- flat for 4 s, then rising at 10 points per second for 3 s (samples every 0.2 s, no gap)
		local s = series(every(0, 7, 0.2), function(t) return t <= 4 and 50 or 50 + 10 * (t - 4) end)
		local slope, _, n = C().Trend(s, 7)
		near(slope, 10, 1e-6)
		eq(n, 16, "the samples from 4.0 s to 7.0 s")
	end)

	it("keeps only the newest 32 samples", function()
		local s = series(every(0, 3, 0.05), function(t) return 10 + 2 * t end)
		eq(s.count, 32)
		local slope, _, n = C().Trend(s, 3)
		near(slope, 2, 1e-6)
		eq(n, 32)
	end)
end)

describe("the trend: confidence from N and R²", function()
	it("is high with 8 samples or more and R² >= 0.8", function()
		local s = series(every(0, 2.8, 0.2), function(t) return 30 + 5 * t + WOBBLE[math.floor(t * 5 + 0.5) + 1] end)
		local slope, confidence, n, r2 = C().Trend(s, 2.8)
		eq(n, 15)
		truthy(r2 >= 0.8, "r2 " .. r2)
		eq(confidence, "high")
		near(slope, 5, 0.6)
	end)

	it("is medium with 5 to 7 samples, or with more samples and R² between 0.5 and 0.8", function()
		local s = series(every(0, 1.2, 0.2), function(t) return 30 + 5 * t end)   -- 7 exact samples
		local _, confidence, n = C().Trend(s, 1.2)
		eq(n, 7)
		eq(confidence, "medium")
		-- 15 samples with a lot of noise around a gentle slope
		local noisy = series(every(0, 2.8, 0.2), function(t) return 30 + 2 * t + 2 * WOBBLE[math.floor(t * 5 + 0.5) + 1] end)
		local _, c2, n2, r2 = C().Trend(noisy, 2.8)
		eq(n2, 15)
		truthy(r2 >= 0.5 and r2 < 0.8, "r2 " .. r2)
		eq(c2, "medium")
	end)

	it("is low with 3 or 4 samples, or with noise that hides the slope", function()
		local s = series({ 0, 0.25, 0.5 }, function(t) return 30 + 5 * t end)
		local slope, confidence, n = C().Trend(s, 0.5)
		near(slope, 5, 1e-9)
		eq(n, 3)
		eq(confidence, "low")
		local noise = series(every(0, 2.8, 0.2), function(t) return 50 + 3 * WOBBLE[math.floor(t * 5 + 0.5) + 1] end)
		local _, c2, _, r2 = C().Trend(noise, 2.8)
		truthy(r2 < 0.5, "r2 " .. r2)
		eq(c2, "low")
	end)
end)

describe("Insufficient data (M2.3 Done when)", function()
	it("needs at least 3 valid samples", function()
		local s = series({ 0, 0.6 }, function(t) return 40 + t end)
		local slope, confidence, n = C().Trend(s, 0.6)
		isNil(slope)
		eq(confidence, "unknown")
		eq(n, 2)
		isNil((C().Trend(C().NewSamples(), 1)))
	end)

	it("needs the samples to cover at least 0.5 s", function()
		local s = series({ 0, 0.1, 0.2, 0.3, 0.4 }, function(t) return 40 + 10 * t end)
		isNil((C().Trend(s, 0.4)))
		C().Push(s, 0.5, 45)
		near((C().Trend(s, 0.5)), 10, 1e-9)
	end)

	it("forgets samples older than 3 s: no fresh samples, no trend", function()
		local s = series(every(0, 2, 0.2), function(t) return 40 + 3 * t end)
		notNil((C().Trend(s, 2)))
		isNil((C().Trend(s, 5.5)), "every sample is more than 3 s old")
	end)
end)

describe("the ring of samples", function()
	it("restarts after a gap of more than 1 s between two valid samples", function()
		local s = series(every(0, 2, 0.2), function(t) return 40 + 3 * t end)
		eq(s.count, 11)
		truthy(C().Push(s, 3.01, 80))
		eq(s.count, 1, "the gap of 1.01 s restarted the ring")
		isNil((C().Trend(s, 3.01)))
		C().Push(s, 3.21, 81)
		eq(s.count, 2)
	end)

	it("keeps going over a gap of exactly 1 s", function()
		local s = series({ 0, 0.2, 1.2 }, function(t) return 40 + t end)
		eq(s.count, 3)
	end)

	it("never takes a duplicate or an older sample (MON-07)", function()
		local s = series({ 1, 1.2, 1.4 }, function(t) return 40 + t end)
		falsy(C().Push(s, 1.4, 99), "same observedAt")
		falsy(C().Push(s, 1.3, 99), "older")
		eq(s.count, 3)
		eq(C().Last(s), 1.4)
		eq(s.p[s.head], 41.4)
	end)

	it("never takes a missing or non-finite value as a number", function()
		local s = C().NewSamples()
		falsy(C().Push(s, 1, nil))
		falsy(C().Push(s, nil, 50))
		falsy(C().Push(s, 1, 0 / 0))
		falsy(C().Push(s, 1, math.huge))
		eq(s.count, 0)
	end)

	it("allocates nothing after it is made", function()
		local s = C().NewSamples()
		collectgarbage("collect")
		collectgarbage("stop")
		local before = collectgarbage("count")
		for i = 1, 2000 do
			C().Push(s, i * 0.2, 50 + (i % 7))
			C().Trend(s, i * 0.2)
		end
		local grown = collectgarbage("count") - before
		collectgarbage("restart")
		truthy(grown < 1, "grew by " .. grown .. " KB")
	end)
end)

describe("the margin (calculated, SPEC-03 §2.2)", function()
	it("is 100 - p for a non tank, and unknown without p", function()
		eq(C().Margin(87), 13)
		eq(C().Margin(100), 0)
		local m, why = C().Margin(nil)
		isNil(m)
		eq(why, "missing")
	end)

	it("is 100 - the second for the tank", function()
		eq(C().TankMargin(72, 3, nil, nil), 28)
	end)

	it("is unknown with the reason 'alone' when no one else is on the list", function()
		local m, why = C().TankMargin(nil, 0, nil, nil)
		isNil(m)
		eq(why, "alone")
	end)

	it("is unknown with the others' reason when no one else is readable", function()
		local m, why = C().TankMargin(nil, 2, "secret", nil)
		isNil(m)
		eq(why, "secret")
	end)

	it("ignores the percentage of lead until the probe gives its meaning [probe P2]", function()
		falsy(C().USE_LEAD)
		eq(C().TankMargin(70, 1, nil, 150), 30)
		local m = C().TankMargin(nil, 1, "secret", 150)
		isNil(m)
	end)
end)

describe("the time to overtake (predicted)", function()
	it("is (100 - p) / trend, rounded up to the second", function()
		eq(C().Overtake(80, 6, "medium"), 4, "20 / 6 = 3.33 s")
		eq(C().Overtake(80, 5, "high"), 4, "exactly 4 s stays 4")
		eq(C().Overtake(99.5, 10, "high"), 1)
	end)

	it("needs a rising trend with at least medium confidence", function()
		local t, why = C().Overtake(80, 0, "high")
		isNil(t)
		eq(why, "not-rising")
		t, why = C().Overtake(80, -3, "high")
		eq(why, "not-rising")
		t, why = C().Overtake(80, 6, "low")
		isNil(t)
		eq(why, "low-confidence")
		t, why = C().Overtake(80, nil, "unknown")
		eq(why, "insufficient")
		t, why = C().Overtake(nil, 6, "high")
		eq(why, "insufficient")
	end)

	it("is shown only within 10 s", function()
		eq(C().Overtake(50, 5, "high"), 10)
		local t, why = C().Overtake(50, 4.9, "high")
		isNil(t)
		eq(why, "beyond")
	end)

	it("says nothing for whoever already has 100 %", function()
		local t, why = C().Overtake(100, 6, "high")
		isNil(t)
		eq(why, "has-aggro")
	end)
end)

describe("the predicted WARNING (SPEC-03 §2.2)", function()
	it("holds when p reaches the DANGER threshold within 3 s", function()
		local on, t = C().PredictedWarning(80, 6, "medium", 95)
		truthy(on)
		near(t, 2.5, 1e-9)
		falsy((C().PredictedWarning(80, 4, "high", 95)), "15 / 4 = 3.75 s")
	end)

	it("needs a rising trend, at least medium confidence and p below the threshold", function()
		falsy((C().PredictedWarning(80, 6, "low", 95)))
		falsy((C().PredictedWarning(80, -6, "high", 95)))
		falsy((C().PredictedWarning(96, 6, "high", 95)))
		falsy((C().PredictedWarning(nil, 6, "high", 95)))
		falsy((C().PredictedWarning(80, nil, "high", 95)))
	end)
end)

describe("freshness (SPEC-03 §1.5, DAT-12)", function()
	it("is stale after max(2 * interval, 0.5 s)", function()
		falsy(C().IsStale(10, 0.2, 10.5), "0.5 s at 5 Hz")
		truthy(C().IsStale(10, 0.2, 10.51))
		falsy(C().IsStale(10, 0.6, 11.2), "a round robin of three turns: 1.2 s")
		truthy(C().IsStale(10, 0.6, 11.21))
	end)

	it("uses 0.5 s for a row with no place in the round robin, and stale for an unknown time", function()
		falsy(C().IsStale(10, nil, 10.5))
		truthy(C().IsStale(10, nil, 10.6))
		truthy(C().IsStale(nil, 0.2, 10))
	end)
end)
