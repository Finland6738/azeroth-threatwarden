end)

describe("saved data of a newer version (read-only)", function()
	before_boot(function(M)
		M.saved = { AzerothThreatwardenDB = { schema = 99, settings = { theme = "aurora" } } }
	end)

	it("says so, changes nothing and writes nothing", function()
		local f = open()
		truthy(f.cards[1]:IsShown())
		contains(f.readOnly:GetText(), "newer version")
		f.theme.control.buttons.warden:Click()
		eq(f.theme.control:Active(), "aurora", "the control goes back")
		contains(f.cards[2].status:GetText(), "Not saved: read-only")
		truthy(f.cards[2].status:IsShown())
		f.reset:Click()
		f.reset:Click()
		eq(f.cards[6].status:GetText(), "Nothing was changed: your saved data is read-only (see /atw debug).")
		deepEq(AzerothThreatwardenDB, { schema = 99, settings = { theme = "aurora" } })
		eq(#Mock.errors, 0)
	end)
end)

describe("the panel in the game's Settings window", function()
	local function panel() return AzerothThreatwarden.Settings.panel end

	it("is registered once at login under the addon's name", function()
		eq(#Mock.settingsCategories, 1)
		eq(Mock.settingsCategories[1].name, "Azeroth Threatwarden")
		eq(Mock.settingsCategories[1].frame, panel())
		truthy(AzerothThreatwarden.Settings.RegisterPanel())
		eq(#Mock.settingsCategories, 1)
		isNil(panel().view, "built the first time it is shown")
	end)

	it("shows the same page, and a change in one shows in the other", function()
		local f = open()
		panel():Show()
		local other = panel().view.settings
		notNil(other)
		other.theme.control.buttons.warden:Click()
		eq(Theme().Current(), "warden")
		eq(f.theme.control:Active(), "warden")
		other.lock.control:Click()
		truthy(f.lock.control:IsOn())
	end)

	it("does not change the page the window remembers", function()
		panel():Show()
		panel().view.pager.buttons.about:Click()
		eq(AzerothThreatwardenCharDB.ui.lastPage, "settings")
	end)

	it("is reported by /atw debug", function()
		contains(AzerothThreatwarden.Diagnostics.Report(), "game settings panel: registered")
	end)
end)

describe("a client without the game's Settings window", function()
	before_boot(function(M) M.Remove("Settings.RegisterCanvasLayoutCategory") end)

	it("keeps the tab and says so in the report", function()
		local ok, why = AzerothThreatwarden.Settings.RegisterPanel()
		falsy(ok)
		eq(why, "unavailable")
		eq(#Mock.settingsCategories, 0)
		contains(AzerothThreatwarden.Diagnostics.Report(), "game settings panel: unavailable")
		open()
		eq(#Mock.errors, 0)
	end)
end)

