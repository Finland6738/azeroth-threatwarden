describe("the Recording card (SPEC-05 §3.6)", function()
	before_boot(function(M)
		M.features = { monitor = true, alerts = true, coach = true, recording = true, reports = true, multitarget = false }
	end)

	local function recording() return account().recording end

	local function addSessions(n)
		local S, St = Mock.ns.Session, Mock.ns.Storage
		for i = 1, n do
			local s = S.New{ id = "c-" .. i, started = 1767225600 + i, rec = {} }
			S.AddUnit(s, { name = "Testchar", token = "player", me = true }, 0)
			S.AddEvent(s, 0, "C", 0, 0, 0, "1")
			S.AddRow(s, 10, 0, 1, nil, "S")
			S.Join(s)
			s.state, s.ended, s.dur, s.fight = "complete", "combat", 100, 100
			St.Add(s)
			St.Closed(s, true)
		end
	end

	local function slide(box, value)
		Mock.RunScript(box.slider, "OnMouseDown")
		box.slider:SetValue(value)
		Mock.RunScript(box.slider, "OnMouseUp")
	end

	it("comes after Alerts and before Reset, with the saved values", function()
		local f = open()
		eq(#f.cards, 8)
		eq(f.cards[7], f.recordingCard)
		truthy(f.recording.control:IsOn())
		eq(f.when:Active(), "group")
		eq(f.recordingRate.value:GetText(), "2 Hz")
		eq(f.rate.value:GetText(), "5 Hz", "the Monitor card keeps its own rate")
		eq(f.maxSessions.value:GetText(), "25")
		eq(f.maxKB.value:GetText(), "2 MB")
		falsy(f.notice.control:IsOn())
		matches(f.usage:GetText(), "^0 recordings · about 0 KB of 2 MB %(estimated%)$")
		contains(f.cards[8].items[2].region:GetText(), "Recordings are not deleted here.")
	end)

	it("writes every control at once", function()
		local f = open()
		f.recording.control:Click()
		eq(recording().enabled, false)
		f.when.buttons.always:Click()
		eq(recording().when, "always")
		slide(f.recordingRate, 4)
		eq(recording().rate, 4)
		eq(account().monitor.rate, 5, "the Monitor card's rate is another control")
		slide(f.maxKB, 700)
		eq(recording().maxKB, 512, "steps of 0.5 MB")
		eq(f.maxKB.value:GetText(), "512 KB")
		slide(f.maxKB, 1536)
		eq(f.maxKB.value:GetText(), "1.5 MB")
		f.notice.control:Click()
		eq(recording().notice, true)
	end)

	it("prunes at once when a limit drops and follows the store", function()
		addSessions(8)
		local f = open()
		contains(f.usage:GetText(), "8 recordings")
		slide(f.maxSessions, 5)
		eq(#AzerothThreatwardenDB.sessions, 5)
		contains(f.usage:GetText(), "5 recordings")
	end)

	it("deletes all with a second click only, and they stay deleted after a /reload", function()
		addSessions(3)
		local f = open()
		f.deleteAll:Click()
		eq(f.deleteAll:GetLabel(), "Click again to delete them all")
		eq(#AzerothThreatwardenDB.sessions, 3)
		f.deleteAll:Click()
		eq(#AzerothThreatwardenDB.sessions, 0)
		contains(f.usage:GetText(), "0 recordings")
		Mock.Reload()
		eq(#AzerothThreatwardenDB.sessions, 0)
	end)

	it("forgets the first click after 8 s and on leaving the page", function()
		addSessions(1)
		local f, view = open()
		f.deleteAll:Click()
		Mock.Advance(9)
		eq(f.deleteAll:GetLabel(), "Delete all recordings")
		f.deleteAll:Click()
		view:ShowPage("about")
		view:ShowPage("settings")
		eq(f.deleteAll:GetLabel(), "Delete all recordings")
		eq(#AzerothThreatwardenDB.sessions, 1)
	end)

	it("says Not saved and deletes nothing on read-only data", function()
		T.boot(function(M)
			M.features = { monitor = true, recording = true, reports = true, multitarget = false }
			M.saved = { AzerothThreatwardenDB = { schema = 99, sessions = {} } }
		end)
		local f = open()
		f.when.buttons.always:Click()
		contains(f.recordingCard.status:GetText(), "Not saved")
		falsy(f.deleteAll:IsEnabled())
		eq(#Mock.errors, 0)
	end)
end)

