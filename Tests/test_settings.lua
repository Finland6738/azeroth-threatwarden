describe("the Monitor card (SPEC-03 §5)", function()
	before_boot(function(M) M.features = { monitor = true } end)

	local function monitor() return account().monitor end

	-- The player moves a thumb and releases it.
	local function slide(box, value)
		Mock.RunScript(box.slider, "OnMouseDown", "LeftButton")
		box.slider:SetValue(value)
		Mock.RunScript(box.slider, "OnMouseUp", "LeftButton")
	end

	it("is there only while the monitor is switched on", function()
		local f = open()
		eq(#f.cards, 6, "Monitor before Reset")
		truthy(f.cards[5]:IsShown())
		notNil(f.warning)
		boot(function(M) M.features = { monitor = false } end)
		local off = open()
		eq(#off.cards, 5)
		isNil(off.warning)
	end)

	it("shows the saved values", function()
		local f = open()
		eq(f.warning.value:GetText(), "80%")
		eq(f.danger.value:GetText(), "95%")
		eq(f.rate.value:GetText(), "5 Hz")
		eq(f.maxUnits.value:GetText(), "40")
		eq(f.show:Active(), "auto")
		eq(f.sort:Selected(), "relative")
		falsy(f.pinSelf.control:IsOn())
		truthy(f.follow.control:IsOn())
		eq(f.demo:GetLabel(), "Start the demo")
		eq(#Mock.errors, 0)
	end)

	it("writes every key", function()
		local seen = {}
		AzerothThreatwarden.Bus.On("SETTINGS_CHANGED", function(key) seen[#seen + 1] = key end)
		local f = open()
		slide(f.warning, 70)
		slide(f.danger, 90)
		slide(f.rate, 8)
		slide(f.maxUnits, 20)
		f.show.buttons.manual:Click()
		f.sort:Select("risk")
		f.pinSelf.control:Click()
		f.follow.control:Click()
		deepEq(monitor(), { warning = 70, danger = 90, rate = 8, maxUnits = 20, show = "manual", sort = "risk",
			pinSelf = true, followTargetOfTarget = false })
		deepEq({ Mock.ns.ThreatState.Thresholds() }, { 70, 90 })
		eq(Mock.ns.ThreatScanner.Rate(), 8)
		eq(Mock.ns.ThreatScanner.MaxUnits(), 20)
		eq(Mock.ns.ThreatList.Sort(), "risk")
		truthy(Mock.ns.ThreatList.PinSelf())
		eq(f.warning.value:GetText(), "70%")
		eq(#seen, 8)
		eq(seen[1], "account.settings.monitor.thresholds")
		eq(seen[3], "account.settings.monitor.rate")
		eq(#Mock.errors, 0)
	end)

	it("saves a slider when it is released, not while it moves", function()
		local f = open()
		Mock.RunScript(f.rate.slider, "OnMouseDown", "LeftButton")
		f.rate.slider:SetValue(9)
		Mock.RunScript(f.rate.slider, "OnValueChanged", 9, true)
		eq(monitor().rate, 5)
		eq(f.rate.value:GetText(), "9 Hz")
		Mock.RunScript(f.rate.slider, "OnMouseUp", "LeftButton")
		eq(monitor().rate, 9)
		Mock.RunScript(f.maxUnits.slider, "OnValueChanged", 15, true)
	end)

	it("pushes the other threshold so that the gap stays", function()
		local f = open()
		slide(f.warning, 93)
		eq(monitor().warning, 93)
		eq(monitor().danger, 98)
		eq(f.danger.value:GetText(), "98%")
		slide(f.danger, 60)
		eq(monitor().warning, 55)
		eq(monitor().danger, 60)
		eq(f.warning.value:GetText(), "55%")
		slide(f.warning, 99)
		eq(monitor().warning, 95, "the highest warning that leaves danger room")
		eq(monitor().danger, 100)
		slide(f.danger, 100)
		eq(monitor().warning, 95)
		eq(#Mock.errors, 0)
	end)

	it("follows a change made elsewhere (the list's header, Reset settings)", function()
		local f = open()
		Mock.ns.ThreatList.SetSort("change")
		eq(monitor().sort, "change", "saved from schema 2 on")
		eq(f.sort:Selected(), "change")
		Mock.ns.ThreatList.SetPinSelf(true)
		truthy(f.pinSelf.control:IsOn())
		Config():Set("account.settings.monitor.rate", 3)
		eq(f.rate.value:GetText(), "3 Hz")
		f.reset:Click()
		f.reset:Click()
		eq(f.sort:Selected(), "relative")
		eq(f.rate.value:GetText(), "5 Hz")
		falsy(f.pinSelf.control:IsOn())
	end)

	it("starts and stops the demo", function()
		local f = open()
		f.demo:Click()
		truthy(Mock.ns.Demo.IsActive())
		eq(W():Tab(), "monitor")
		eq(account().lastTab, nil)
		eq(AzerothThreatwardenCharDB.ui.lastTab, "settings")
		eq(f.demo:GetLabel(), "Stop the demo")
		W():SelectTab("settings")
		f.demo:Click()
		falsy(Mock.ns.Demo.IsActive())
		eq(f.demo:GetLabel(), "Start the demo")
	end)

	it("changes nothing on read-only data, and says why", function()
		boot(function(M)
			M.features = { monitor = true }
			M.saved = { AzerothThreatwardenDB = { schema = 99 } }
		end)
		local f = open()
		slide(f.warning, 60)
		contains(f.cards[5].status:GetText(), "Not saved")
		eq(f.warning.value:GetText(), "80%")
		f.show.buttons.always:Click()
		eq(f.show:Active(), "auto")
		f.pinSelf.control:Click()
		falsy(f.pinSelf.control:IsOn())
	end)

	it("says in the Reset card that the monitor settings go back too", function()
		local f = open()
		local text = {}
		for _, it in ipairs(f.cards[6].items) do
			if it.region.GetText then text[#text + 1] = it.region:GetText() end
		end
		contains(table.concat(text, "\n"), "the monitor back to the defaults")
	end)

	it("is in Italian on an Italian client", function()
		boot(function(M) M.features = { monitor = true }; M.player.locale = "itIT" end)
		local f = open()
		eq(f.demo:GetLabel(), "Avvia la demo")
		eq(f.show.buttons.always.label:GetText(), "Sempre")
		eq(f.rate.value:GetText(), "5 Hz")
		eq(#Mock.errors, 0)
	end)
end)
