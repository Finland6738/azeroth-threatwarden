-- UI/Settings.lua (SPEC-03 §5): the Settings tab and the panel of the game's own Settings window. Every setting
-- applies at once, except the font (complete after a restart) and the language (after /reload).

local function W() return AzerothThreatwarden.Window end
local function Config() return AzerothThreatwarden.Config end
local function Theme() return AzerothThreatwarden.Theme end
local function account() return AzerothThreatwardenDB.settings end

-- The window's Settings page: the view and its controls.
local function open()
	W():OpenPage("settings")
	local view = W():Frame().pages.settings.view
	return view.settings, view
end

local function icon() return LibStub("LibDBIcon-1.0"):GetMinimapButton("AzerothThreatwarden") end

describe("the Settings page", function()
	it("is built when the tab is first shown, with the cards of SPEC-03", function()
		isNil(W():Frame().pages.settings.view, "nothing built while the Monitor is on screen")
		local f, view = open()
		eq(view.pageId, "settings")
		eq(#f.cards, 6, "read-only warning, Appearance, Language, Window, Monitor, Reset")
		falsy(f.cards[1]:IsShown(), "no warning on writable data")
		for i = 2, 6 do truthy(f.cards[i]:IsShown()) end
		eq(view.pager:Active(), "settings")
		eq(#Mock.errors, 0)
	end)

	it("shows the saved values", function()
		local f = open()
		eq(f.theme.control:Active(), "nebula")
		truthy(f.effects.control:IsOn())
		truthy(f.animations.control:IsOn())
		eq(f.font.control:Active(), "addon")
		eq(f.language:Active(), "auto")
		falsy(f.lock.control:IsOn())
		eq(f.scaleBox.value:GetText(), "100%")
		truthy(f.minimap.control:IsOn())
	end)

	it("raises SETTINGS_CHANGED with the key the player changed", function()
		local seen = {}
		AzerothThreatwarden.Bus.On("SETTINGS_CHANGED", function(key) seen[#seen + 1] = key end)
		local f = open()
		f.theme.control.buttons.aurora:Click()
		f.lock.control:Click()
		deepEq(seen, { "account.settings.theme", "char.ui.locked" })
	end)

	it("keeps the column at most 520 wide and narrows it with the window", function()
		local f, view = open()
		eq(f.cards[2]:GetWidth(), 520)
		Mock.RunScript(view, "OnSizeChanged", 440, 400)
		eq(f.cards[2]:GetWidth(), 440)
		Mock.RunScript(view, "OnSizeChanged", 900, 400)
		eq(f.cards[2]:GetWidth(), 520)
	end)

	it("scrolls with the wheel and never above the top", function()
		local f = open()
		local scroll = f.page.scroll
		Mock.RunScript(scroll, "OnMouseWheel", -1)
		eq(scroll:GetVerticalScroll(), 40)
		Mock.RunScript(scroll, "OnMouseWheel", 3)
		eq(scroll:GetVerticalScroll(), 0)
	end)
end)

describe("the Appearance card", function()
	it("changes the theme at once", function()
		local f = open()
		for _, id in ipairs({ "aurora", "warden", "nebula" }) do
			f.theme.control.buttons[id]:Click()
			eq(account().theme, id)
			eq(Theme().Current(), id)
			local r, g, b = Theme().Color("bg", id)
			local sr, sg, sb = W():Frame().skins.wide.parts.fill:GetVertexColor()
			deepEq({ sr, sg, sb }, { r, g, b }, "the window is repainted: " .. id)
		end
	end)

	it("turns the glows off and on at once", function()
		local f = open()
		local glow = W():Frame().titles.wide.logoGlow
		truthy(glow:IsShown())
		f.effects.control:Click()
		eq(account().effects, false)
		falsy(glow:IsShown())
		f.effects.control:Click()
		truthy(glow:IsShown())
	end)

	it("turns the animations off at once", function()
		local f = open()
		truthy(AzerothThreatwarden.Motion.On())
		f.animations.control:Click()
		eq(account().animations, false)
		falsy(AzerothThreatwarden.Motion.On())
	end)

	it("saves the font and says that it needs a restart", function()
		local f = open()
		f.font.control.buttons.game:Click()
		eq(account().font, "game")
		eq(Theme().fontStatus.Body, "game")
		contains(f.fontNote:GetText(), "restart")
		f.font.control.buttons.addon:Click()
		eq(account().font, "addon")
	end)

	it("follows a change made elsewhere", function()
		local f = open()
		Config():Set("account.settings.theme", "warden")
		eq(f.theme.control:Active(), "warden")
	end)
end)

describe("the Language card", function()
	it("saves the choice, which applies after a reload", function()
		local f = open()
		falsy(f.reload:IsEnabled(), "nothing to reload yet")
		f.language.buttons.itIT:Click()
		eq(account().language, "itIT")
		eq(AzerothThreatwarden.Locale.Active(), "enUS")
		truthy(f.reload:IsEnabled())
		f.reload:Click()
		eq(Mock.reloads, 1)
		Mock.Reload()
		eq(AzerothThreatwarden.Locale.Active(), "itIT")
		local after = open()
		eq(after.language:Active(), "itIT")
		eq(after.reset:GetLabel(), "Ripristina impostazioni")
		falsy(after.reload:IsEnabled())
	end)

	it("needs no reload for the language already on screen", function()
		local f = open()
		f.language.buttons.enUS:Click()
		eq(account().language, "enUS")
		falsy(f.reload:IsEnabled())
	end)
end)

describe("the Window card", function()
	it("locks the window, and follows the lock of the title bar", function()
		local f = open()
		f.lock.control:Click()
		eq(AzerothThreatwardenCharDB.ui.locked, true)
		falsy(W():Frame().grip:IsShown())
		W():Frame().titles.wide.lock:Click()
		eq(AzerothThreatwardenCharDB.ui.locked, false)
		falsy(f.lock.control:IsOn())
	end)

	it("shows the scale while the thumb moves and applies it on release", function()
		local f = open()
		local slider = f.scaleBox.slider
		Mock.RunScript(slider, "OnMouseDown", "LeftButton")
		slider:SetValue(125)
		Mock.RunScript(slider, "OnValueChanged", 125, true)
		eq(f.scaleBox.value:GetText(), "125%")
		eq(AzerothThreatwardenCharDB.ui.scale, 1)
		Mock.RunScript(slider, "OnMouseUp", "LeftButton")
		eq(AzerothThreatwardenCharDB.ui.scale, 1.25)
		eq(W():Frame():GetScale(), 1.25)
	end)

	it("applies a click on the track at once", function()
		local f = open()
		f.scaleBox.slider:SetValue(80)
		Mock.RunScript(f.scaleBox.slider, "OnValueChanged", 80, true)
		eq(AzerothThreatwardenCharDB.ui.scale, 0.8)
		eq(W():Frame():GetScale(), 0.8)
	end)

	it("hides and shows the minimap button at once", function()
		local f = open()
		truthy(icon():IsShown())
		f.minimap.control:Click()
		eq(account().minimap.hide, true)
		falsy(icon():IsShown())
		f.minimap.control:Click()
		truthy(icon():IsShown())
	end)

	it("resets the window", function()
		local f = open()
		Config():Set("char.ui.scale", 1.5)
		eq(f.scaleBox.value:GetText(), "150%")
		f.resetWindow:Click()
		eq(AzerothThreatwardenCharDB.ui.scale, 1)
		eq(f.scaleBox.value:GetText(), "100%")
		eq(f.cards[4].status:GetText(), "Window position, size and scale reset.")
		truthy(W():IsShown())
	end)
end)

describe("Reset settings", function()
	local function changeAll()
		Config():Set("account.settings.theme", "aurora")
		Config():Set("account.settings.effects", false)
		Config():Set("account.settings.minimap.hide", true)
		Config():Set("char.ui.scale", 1.5)
	end

	it("asks for a second click, then puts the account settings back", function()
		changeAll()
		local f = open()
		f.reset:Click()
		eq(account().theme, "aurora", "one click changes nothing")
		eq(f.reset:GetLabel(), "Click again to reset")
		f.reset:Click()
		eq(account().theme, "nebula")
		eq(account().effects, true)
		eq(account().minimap.hide, false)
		eq(AzerothThreatwardenCharDB.ui.scale, 1.5, "the window is not a setting of the account")
		eq(Theme().Current(), "nebula")
		eq(f.theme.control:Active(), "nebula")
		truthy(f.minimap.control:IsOn())
		eq(f.reset:GetLabel(), "Reset settings")
		eq(f.cards[6].status:GetText(), "Settings reset.")
	end)

	it("forgets the first click after a few seconds", function()
		changeAll()
		local f = open()
		f.reset:Click()
		Mock.Advance(9)
		eq(f.reset:GetLabel(), "Reset settings")
		f.reset:Click()
		eq(account().theme, "aurora")
	end)

	it("forgets the first click when the page is left", function()
		changeAll()
		local f, view = open()
		f.reset:Click()
		view.pager.buttons.about:Click()
		view.pager.buttons.settings:Click()
		f.reset:Click()
		eq(account().theme, "aurora")
	end)
end)

describe("the page selector", function()
	it("opens Info and remembers it for the character", function()
		local f, view = open()
		view.pager.buttons.about:Click()
		eq(view.pageId, "about")
		eq(AzerothThreatwardenCharDB.ui.lastPage, "about")
		falsy(view.holders.settings:IsShown())
