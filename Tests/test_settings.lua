describe("the Alerts card", function()
	before_boot(function(M) M.features = { monitor = true, alerts = true, coach = true, recording = false, multitarget = false } end)

	it("stands after Monitor and before Reset", function()
		local f = open()
		eq(#f.cards, 7)
		eq(f.cards[5], f.monitorCard)
		eq(f.cards[6], f.alertsCard)
		truthy(f.alertsCard:IsShown())
		contains(f.cards[7].items[2].region:GetText(), "alerts and Coach")
	end)

	it("shows the defaults", function()
		local f = open()
		truthy(f.alertsEnabled.control:IsOn())
		truthy(f.alertsWindow.control:IsOn())
		truthy(f.alertsVisual.control:IsOn())
		falsy(f.alertsSound.control:IsOn())
		eq(f.cooldown.value:GetText(), "8 s")
		eq(f.others:Active(), "tank")
		truthy(f.alertsPet.control:IsOn())
		truthy(f.coach.control:IsOn())
		eq(f.thresholds:GetText(), "Alerts follow the monitor's thresholds: Warning 82 %, Danger 91 %.")
	end)

	it("saves every control at once", function()
		local seen = {}
		AzerothThreatwarden.Bus.On("SETTINGS_CHANGED", function(key) seen[#seen + 1] = key end)
		local f = open()
		f.alertsWindow.control:Click()
		f.alertsVisual.control:Click()
		f.alertsSound.control:Click()
		f.others.buttons.never:Click()
		f.alertsPet.control:Click()
		f.coach.control:Click()
		f.alertsEnabled.control:Click()
		local a = alertsAccount()
		eq(a.window, false)
		eq(a.visual, false)
		eq(a.sound, true)
		eq(a.others, "never")
		eq(a.pet, false)
		eq(a.enabled, false)
		eq(AzerothThreatwardenDB.settings.coach.enabled, false)
		eq(#seen, 7)
		contains(seen, "account.settings.coach.enabled")
		eq(#Mock.errors, 0)
	end)

	it("applies at once to the alerts, the strip and the Coach", function()
		local f = open()
		f.alertsSound.control:Click()
		contains(table.concat(Mock.ns.Alerts.DebugLines(), "\n"), "sound yes")
		contains(table.concat(Mock.ns.Alerts.DebugLines(), "\n"), "scanner wanted: yes")
		f.coach.control:Click()
		falsy(Mock.ns.Coach.Enabled())
		truthy(Mock.ns.CoachStrip.Present(), "the alerts keep the strip")
		f.alertsEnabled.control:Click()
		falsy(Mock.ns.CoachStrip.Present())
		contains(table.concat(Mock.ns.Alerts.DebugLines(), "\n"), "scanner wanted: no")
		eq(Mock.ns.Alerts.ToggleMute(), "disabled")
	end)

	it("keeps the channels on screen but inactive while the alerts are off", function()
		local f = open()
		f.alertsEnabled.control:Click()
		for _, row in ipairs({ f.alertsWindow, f.alertsVisual, f.alertsSound }) do
			truthy(row:IsShown())
			falsy(row.control:IsEnabled())
			row.control:Click()
