-- UI/Settings.lua (SPEC-03 §5): the Settings tab and the panel of the game's own Settings window. Every setting
-- applies at once, except the font (complete after a restart) and the language (after /reload).

local function W() return AzerothThreatwarden.Window end
local function Config() return AzerothThreatwarden.Config end
local function Theme() return AzerothThreatwarden.Theme end
local function account() return AzerothThreatwardenDB.settings end

-- The window's Settings page: the view and its controls.
local function open()
	W():OpenPage("settings")
	local view = W():Frame().pages.settings.view
	return view.settings, view
end

local function icon() return LibStub("LibDBIcon-1.0"):GetMinimapButton("AzerothThreatwarden") end

describe("the Settings page", function()
	it("is built when the tab is first shown, with the cards of SPEC-03", function()
		isNil(W():Frame().pages.settings.view, "nothing built while the Monitor is on screen")
		local f, view = open()
		eq(view.pageId, "settings")
		eq(#f.cards, 9, "read-only warning, Appearance, Language, Window, Monitor, Dungeon Focus, Alerts, Recording, Reset")
		falsy(f.cards[1]:IsShown(), "no warning on writable data")
		for i = 2, 9 do truthy(f.cards[i]:IsShown()) end
		eq(view.pager:Active(), "settings")
		eq(#Mock.errors, 0)
	end)

	it("shows the saved values", function()
		local f = open()
		eq(f.theme.control:Active(), "nebula")
		truthy(f.effects.control:IsOn())
		truthy(f.animations.control:IsOn())
		eq(f.font.control:Active(), "addon")
		eq(f.language:Active(), "auto")
		falsy(f.lock.control:IsOn())
		eq(f.scaleBox.value:GetText(), "100%")
		truthy(f.minimap.control:IsOn())
	end)

	it("raises SETTINGS_CHANGED with the key the player changed", function()
		local seen = {}
		AzerothThreatwarden.Bus.On("SETTINGS_CHANGED", function(key) seen[#seen + 1] = key end)
		local f = open()
		f.theme.control.buttons.aurora:Click()
		f.lock.control:Click()
		deepEq(seen, { "account.settings.theme", "char.ui.locked" })
	end)

	it("keeps the column at most 520 wide and narrows it with the window", function()
		local f, view = open()
		eq(f.cards[2]:GetWidth(), 520)
		Mock.RunScript(view, "OnSizeChanged", 440, 400)
		eq(f.cards[2]:GetWidth(), 440)
		Mock.RunScript(view, "OnSizeChanged", 900, 400)
		eq(f.cards[2]:GetWidth(), 520)
	end)

	it("scrolls with the wheel and never above the top", function()
		local f = open()
		local scroll = f.page.scroll
		Mock.RunScript(scroll, "OnMouseWheel", -1)
		eq(scroll:GetVerticalScroll(), 40)
		Mock.RunScript(scroll, "OnMouseWheel", 3)
		eq(scroll:GetVerticalScroll(), 0)
	end)
end)

describe("the Appearance card", function()
	it("changes the theme at once", function()
		local f = open()
		for _, id in ipairs({ "aurora", "warden", "nebula" }) do
			f.theme.control.buttons[id]:Click()
			eq(account().theme, id)
			eq(Theme().Current(), id)
			local r, g, b = Theme().Color("bg", id)
			local sr, sg, sb = W():Frame().skins.wide.parts.fill:GetVertexColor()
			deepEq({ sr, sg, sb }, { r, g, b }, "the window is repainted: " .. id)
		end
	end)

	it("turns the glows off and on at once", function()
		local f = open()
		local glow = W():Frame().titles.wide.logoGlow
		truthy(glow:IsShown())
		f.effects.control:Click()
		eq(account().effects, false)
		falsy(glow:IsShown())
		f.effects.control:Click()
		truthy(glow:IsShown())
	end)

	it("turns the animations off at once", function()
		local f = open()
		truthy(AzerothThreatwarden.Motion.On())
		f.animations.control:Click()
		eq(account().animations, false)
		falsy(AzerothThreatwarden.Motion.On())
	end)

	it("saves the font and says that it needs a restart", function()
		local f = open()
		f.font.control.buttons.game:Click()
		eq(account().font, "game")
		eq(Theme().fontStatus.Body, "game")
		contains(f.fontNote:GetText(), "restart")
		f.font.control.buttons.addon:Click()
		eq(account().font, "addon")
	end)

	it("follows a change made elsewhere", function()
		local f = open()
		Config():Set("account.settings.theme", "warden")
		eq(f.theme.control:Active(), "warden")
	end)
end)

