describe("the screen's edges", function()
	it("computes where a window is from any anchor", function()
		deepEq({ W().Rect(nil, 300, 200, 1000, 800) }, { 350, 500 })
		deepEq({ W().Rect({ point = "TOPRIGHT", relativePoint = "TOPRIGHT", x = -10, y = -20 }, 300, 200, 1000, 800) },
			{ 690, 780 })
		deepEq({ W().Rect({ point = "BOTTOM", relativePoint = "LEFT", x = 0, y = 0 }, 300, 200, 1000, 800) },
			{ -150, 600 })
		deepEq({ W().Clamp(-5, 900, 300, 200, 1000, 800) }, { 0, 800 })
		deepEq({ W().Clamp(900, 100, 300, 200, 1000, 800) }, { 700, 200 })
		deepEq({ W().Clamp(50, 100, 1200, 900, 1000, 800) }, { 0, 800 })
	end)

	it("brings the window back inside when the screen shrinks, without forgetting its place", function()
		drag("compact", { "TOPLEFT", "BOTTOMLEFT", 1500, 1000 })
		UIParent:SetSize(1280, 720)
		Mock.Fire("DISPLAY_SIZE_CHANGED")
		deepEq(point(), { "TOPLEFT", "BOTTOMLEFT", 980, 720 })
		deepEq(ui().pos, { point = "TOPLEFT", relativePoint = "BOTTOMLEFT", x = 1500, y = 1000 })
		UIParent:SetSize(1920, 1080)
		W():Close()
	end)

	it("answers a change of the interface scale", function()
		drag("compact", { "TOPLEFT", "BOTTOMLEFT", -50, 500 })
		Mock.Fire("UI_SCALE_CHANGED")
		deepEq(point(), { "TOPLEFT", "BOTTOMLEFT", 0, 500 })
	end)
end)

