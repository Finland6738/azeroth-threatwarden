-- UI/Window.lua (SPEC-03 §4): the window of the addon, its two layouts, move, lock, resize, scale, position and size
-- per character through a /reload, Esc, the module state and the screen's edges.

local function W() return AzerothThreatwarden.Window end
local function F() return W():Frame() end
local function Config() return AzerothThreatwarden.Config end
local function ui() return AzerothThreatwardenCharDB.ui end

-- What the player does with the mouse: drag the title bar to a place, or pull the grip to a size.
local function drag(layout, pos)
	local f = F()
	local bar = f.titles[layout]
	Mock.RunScript(bar, "OnDragStart", "LeftButton")
	local moving = f._moving
	if moving and pos then
		f:ClearAllPoints()
		f:SetPoint(pos[1], UIParent, pos[2], pos[3], pos[4])
	end
	Mock.RunScript(bar, "OnDragStop")
	return moving
end

local function pull(w, h)
	local f = F()
	Mock.RunScript(f.grip, "OnMouseDown", "LeftButton")
	local sizing = f._sizing
	if sizing then f:SetSize(w, h) end
	Mock.RunScript(f.grip, "OnMouseUp", "LeftButton")
	return sizing
end

local function point()
	local p, _, rel, x, y = F():GetPoint(1)
	return { p, rel, x, y }
end

