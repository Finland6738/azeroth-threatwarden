describe("when the window shows itself (SPEC-03 §5.1, Q13)", function()
	before_boot(function(M) M.features = { monitor = true } end)

	local function show(mode) truthy(Config():Set("account.settings.monitor.show", mode)) end
	local function join()
		if not Mock.units.Get("tank") then Mock.units.Add("tank", { class = "WARRIOR", role = "TANK" }) end
		Mock.group.Set{ members = { "tank" } }
	end
	local function closed(setup)
		boot(function(M)
			M.features = { monitor = true }
			M.saved = { AzerothThreatwardenCharDB = { schema = 1, ui = { shown = false, lastTab = "settings" } } }
			if setup then setup(M) end
		end)
	end
	local function fight() Mock.combat.Enter() end
	local function over() Mock.combat.Leave() end

	it("is 'auto' by default", function()
		eq(W().ShowMode(), "auto")
	end)

	it("auto: opens at a fight, on the Monitor tab, without saving anything", function()
		closed()
		falsy(W():IsShown())
		fight()
		truthy(W():IsShown())
		eq(W():Tab(), "monitor")
		eq(ui().shown, false)
		eq(ui().lastTab, "settings")
		isNil(ui().pos)
		eq(#Mock.errors, 0)
	end)

	it("auto: closes itself 10 s after a fight outside a group, without saving it", function()
		truthy(W():IsShown())
		fight()
		over()
		Mock.Advance(9.9)
		truthy(W():IsShown())
		Mock.Advance(0.2)
		falsy(W():IsShown())
		eq(ui().shown, true, "the player's own choice stays")
		fight()
		truthy(W():IsShown(), "and opens again at the next fight")
	end)

	it("auto: a new fight cancels the closing", function()
		fight()
		over()
		Mock.Advance(5)
		fight()
		Mock.Advance(20)
		truthy(W():IsShown())
		over()
		Mock.Advance(10.1)
		falsy(W():IsShown())
	end)

	it("auto: stays open in a group, and when a group is joined within the 10 s", function()
		join()
		fight()
		over()
		Mock.Advance(30)
		truthy(W():IsShown())
		Mock.group.Leave()
		fight()
		over()
		Mock.Advance(5)
		join()
		Mock.Advance(30)
		truthy(W():IsShown())
	end)

	it("auto: stays open on another tab, and when the player opens it again", function()
		fight()
		over()
		W():SelectTab("settings")
		Mock.Advance(30)
		truthy(W():IsShown())
		W():SelectTab("monitor")
		fight()
		over()
		W():Open()
		Mock.Advance(30)
		truthy(W():IsShown())
	end)

	it("auto: opens on joining a group, once", function()
		closed()
		join()
		truthy(W():IsShown())
		eq(ui().shown, false)
		W():Close()
		Mock.Fire("GROUP_ROSTER_UPDATE")
		falsy(W():IsShown(), "still the same group")
		Mock.group.Leave()
		join()
		truthy(W():IsShown(), "a new group")
	end)

	it("auto: closed by the player in a fight, it stays closed until the next fight", function()
		fight()
		W():Close()
		eq(ui().shown, false)
		join()
		falsy(W():IsShown())
		over()
		Mock.group.Leave()
		join()
		falsy(W():IsShown())
		fight()
		truthy(W():IsShown())
	end)

	it("auto: Esc in a fight counts as closing", function()
		fight()
		F():Hide()
		eq(ui().shown, false)
		join()
		falsy(W():IsShown())
	end)

	it("auto: opens at login in a group, and in a fight", function()
		closed(function(M)
			M.OnFilesLoaded(function()
				M.units.Add("tank", { class = "WARRIOR", role = "TANK" })
				M.group.Set{ members = { "tank" } }
			end)
		end)
		truthy(W():IsShown())
		eq(ui().shown, false)
		Mock.group.Leave()
		closed()
		falsy(W():IsShown())
		fight()
		W():Close()
		Mock.Reload()
		truthy(W():IsShown(), "a reload in a fight")
	end)

	it("always: shown at login and when chosen, closed only by hand", function()
		closed()
		show("always")
		truthy(W():IsShown())
		eq(ui().shown, false)
		fight()
		over()
		Mock.Advance(30)
		truthy(W():IsShown())
		W():Close()
		fight()
		falsy(W():IsShown())
		Mock.Reload()
		truthy(W():IsShown())
	end)

	it("manual: neither opens nor closes by itself", function()
		show("manual")
		fight()
		over()
		Mock.Advance(30)
		truthy(W():IsShown())
		W():Close()
		fight()
		join()
		falsy(W():IsShown())
		Mock.Reload()
		falsy(W():IsShown())
	end)

	it("choosing another mode cancels a pending closing", function()
		fight()
		over()
		show("manual")
		Mock.Advance(30)
		truthy(W():IsShown())
	end)

	it("follows the same rules on read-only data, writing nothing", function()
		boot(function(M)
			M.features = { monitor = true }
			M.saved = { AzerothThreatwardenCharDB = { schema = 99 } }
		end)
		fight()
		over()
		Mock.Advance(10.1)
		falsy(W():IsShown())
		fight()
		truthy(W():IsShown())
		deepEq(AzerothThreatwardenCharDB, { schema = 99 })
	end)

	it("a running demo is not closed", function()
		fight()
		over()
		Mock.ns.Demo.Start()
