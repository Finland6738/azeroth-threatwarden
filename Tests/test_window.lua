describe("moving and resizing", function()
	it("saves the position when the title bar is released", function()
		truthy(drag("compact", { "TOPLEFT", "TOPLEFT", 40, -60 }))
		deepEq(ui().pos, { point = "TOPLEFT", relativePoint = "TOPLEFT", x = 40, y = -60 })
		falsy(F()._moving)
	end)

	it("saves the size of the layout in use, within its limits", function()
		truthy(pull(420, 300))
		deepEq(ui().size.compact, { w = 420, h = 300 })
		isNil(ui().size.wide)
		pull(5000, 10)
		deepEq(ui().size.compact, { w = 600, h = 140 })
		deepEq({ F():GetSize() }, { 600, 140 })
		W():SelectTab("settings")
		pull(700, 600)
		deepEq(ui().size.wide, { w = 700, h = 600 })
		W():SelectTab("monitor")
		deepEq({ F():GetSize() }, { 600, 140 })
	end)

	it("does neither while locked, hides the grip and shows the closed lock", function()
		local bar = F().titles.compact
		local open = { bar.lock.icon._texCoord[1], bar.lock.icon._texCoord[3] }
		bar.lock:Click()
		eq(ui().locked, true)
		ne(bar.lock.icon._texCoord[1] .. ":" .. bar.lock.icon._texCoord[3], open[1] .. ":" .. open[2])
		falsy(F().grip:IsShown())
		falsy(drag("compact", { "TOPLEFT", "TOPLEFT", 40, -60 }))
		falsy(pull(420, 300))
		isNil(ui().pos)
		isNil(ui().size.compact)
		bar.lock:Click()
		eq(ui().locked, false)
		truthy(F().grip:IsShown())
		truthy(drag("compact"))
	end)

	it("ends a drag when the window is closed in the middle of it", function()
		local f = F()
		Mock.RunScript(f.titles.compact, "OnDragStart")
		f:Hide()
		falsy(f._moving)
	end)

	it("applies a scale and keeps a moved window where it is", function()
		drag("compact", { "TOPLEFT", "BOTTOMLEFT", 200, 800 })
		truthy(Config():Set("char.ui.scale", 2))
		eq(F():GetScale(), 2)
		deepEq(point(), { "TOPLEFT", "BOTTOMLEFT", 100, 400 })
		deepEq(ui().pos, { point = "TOPLEFT", relativePoint = "BOTTOMLEFT", x = 100, y = 400 })
	end)

	it("follows the lock and the position set elsewhere (Settings)", function()
		F()
		Config():Set("char.ui.locked", true)
		falsy(F().grip:IsShown())
		Config():Set("char.ui.pos", { point = "CENTER", relativePoint = "CENTER", x = 10, y = 20 })
